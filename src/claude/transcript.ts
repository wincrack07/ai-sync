export interface ClaudeTarget { path: string; sessionId: string; cwd: string; leafUuid: string | null; template: Record<string, unknown>; model?: string; }

/** A record we are about to write, with its uuid known up front for the ledger's write-ahead entry. */
export interface PlannedClaudeRecord { uuid: string; msg: CanonMsg; }

export function planClaudeRecords(msgs: CanonMsg[]): PlannedClaudeRecord[] {
  return msgs.map((m) => ({ uuid: uuid(), msg: m }));
}

export function buildClaudeRecords(target: ClaudeTarget, planned: PlannedClaudeRecord[], src: 'codex'): any[] {
  let parent = target.leafUuid;
  const base = { userType: 'external', version: '0.0.0', ...target.template };
  return planned.map(({ uuid: u, msg }) => {
    const ts = msg.timestamp || new Date().toISOString();
    const common = {
      parentUuid: parent, isSidechain: false, ...base,
      cwd: target.cwd, sessionId: target.sessionId, uuid: u, timestamp: ts,
      aiSync: { v: 1, src, id: msg.id },
    };
    parent = u;
    if (msg.role === 'user') return { ...common, type: 'user', message: { role: 'user', content: msg.text } };
    return {
      ...common, type: 'assistant',
      message: {
        id: `msg_aisync_${sha(u, 20)}`, type: 'message', role: 'assistant', model: target.model ?? 'codex-via-ai-sync',
        content: [{ type: 'text', text: msg.text }], stop_reason: 'end_turn', stop_sequence: null,
        usage: { input_tokens: 0, output_tokens: 0, cache_creation_input_tokens: 0, cache_read_input_tokens: 0 },
      },
    };
  });
}

/** ClaudeTranscriptWriterPort: append mirrored messages to an existing transcript. */
export function appendClaude(target: ClaudeTarget, planned: PlannedClaudeRecord[]): void {
  appendJsonl(target.path, buildClaudeRecords(target, planned, 'codex'));
}

/** ClaudeCardWriterPort: write the title card so the session is recognisable in `claude --resume`. */
export function writeClaudeTitle(file: string, sessionId: string, title: string): void {
  appendJsonl(file, [{ type: 'custom-title', customTitle: title, sessionId }]);
}

/** Create a brand-new transcript for a Codex thread. Returns the target for subsequent appends. */
export function newClaudeTarget(claudeDir: string, cwd: string, template: Record<string, unknown>): ClaudeTarget {
  const sessionId = uuid();
  const dir = path.join(claudeDir, 'projects', projectSlug(cwd || '/'));
  return { path: path.join(dir, `${sessionId}.jsonl`), sessionId, cwd: cwd || '/', leafUuid: null, template };
}

/** Find any recent real record to copy version/userType from, so our records look like the installed Claude Code. */
export function findClaudeTemplate(files: string[]): Record<string, unknown> {
  const sorted = files.map((f) => { try { return [f, fs.statSync(f).mtimeMs] as const; } catch { return [f, 0] as const; } })
    .sort((a, b) => b[1] - a[1]).slice(0, 5);
  for (const [f] of sorted) {
    const lines = readJsonl(f);
    for (let i = lines.length - 1; i >= 0; i--) {
      const r = lines[i].obj;
      if ((r?.type === 'user' || r?.type === 'assistant') && r.version && !r.aiSync) return pickTemplate(r);
    }
  }
  return {};
}
